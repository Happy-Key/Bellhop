/**
 * Customer text chat: the same conversation as a voice call, typed. A chat session is a voice
 * session with channel "text", so each message goes through the same path as a call's utterance
 * (recordVoiceUtterance → takeTurn): it is recorded as a statement linked to the question it
 * answers, then the next question comes from a reviewer, the reasoning model, or the rules.
 *
 * The case comes from the backend-issued session token, never from the message. DEMO ONLY: as on
 * the call page, any case can be continued, since there are no customer logins.
 */
import { v } from "convex/values";
import { action, mutation, query } from "./_generated/server";
import type { GenericActionCtx } from "convex/server";
import type { DataModel } from "./_generated/dataModel";
import { internal } from "./_generated/api";
import { logActivity } from "./model";
import { VOICE_SESSION_TTL_MS, issueNextQuestion, type VoiceToolResponse } from "./voice";
import { takeTurn } from "./intakeTurn";
import { modelQuestionFor } from "./proposals";
import { openReviewerQuestions } from "./reviewerQuestions";

const MESSAGE_ID = /^[A-Za-z0-9_-]{8,64}$/;
const MAX_MESSAGE_CHARS = 2000;

/**
 * Opens a chat on a case. On a case the customer has already reported, the first question the
 * bank is waiting on is issued right away (recorded like a call's question), so the customer's
 * first reply is linked to it. A new case opens with "what happened?" instead.
 */
export const startChat = mutation({
  args: { caseId: v.id("cases") },
  handler: async (ctx, { caseId }) => {
    const c = await ctx.db.get(caseId);
    if (!c) throw new Error("case not found");
    const token = `vs_${crypto.randomUUID().replace(/-/g, "")}`;
    const now = Date.now();
    const sessionId = await ctx.db.insert("voiceSessions", { token, caseId, createdAt: now, expiresAt: now + VOICE_SESSION_TTL_MS, channel: "text" });
    await logActivity(ctx, caseId, "system", "chat_session_created", "Text chat session started (expires in 30 min).");
    const reported = (await ctx.db.query("statements").withIndex("by_case", (q) => q.eq("caseId", caseId)).first()) !== null;
    const opening = reported ? await issueNextQuestion(ctx, (await ctx.db.get(sessionId))!, c) : null;
    return { token, expiresAt: now + VOICE_SESSION_TTL_MS, opening: opening ? { questionId: opening.turnId as string, text: opening.text } : null, reported };
  },
});

/**
 * One customer message. `messageId` is generated by the browser per message, so a retried send is
 * recorded once and gets the same reply. `questionId` echoes the last reply's question_id.
 */
export const send = action({
  args: { sessionToken: v.string(), text: v.string(), messageId: v.string(), questionId: v.optional(v.string()) },
  handler: async (ctx, args): Promise<VoiceToolResponse> => sendChatMessage(ctx, args),
});

/** One chat message, as `send` handles it (also used by the claim suite runner, convex/suite.ts). */
export async function sendChatMessage(
  ctx: Pick<GenericActionCtx<DataModel>, "runQuery" | "runMutation">,
  { sessionToken, text, messageId, questionId }: { sessionToken: string; text: string; messageId: string; questionId?: string },
): Promise<VoiceToolResponse> {
  if (!MESSAGE_ID.test(messageId)) throw new Error("invalid message id");
  const t = text.trim();
  if (!t) throw new Error("the message is empty");
  if (t.length > MAX_MESSAGE_CHARS) throw new Error(`keep messages under ${MAX_MESSAGE_CHARS} characters`);
  const result = await ctx.runMutation(internal.voice.recordVoiceUtterance, {
    sessionToken,
    utterance: t,
    utteranceKey: `msg-${messageId}`,
    ...(questionId ? { questionId } : {}),
  });
  if (!result.ok) throw new Error("This chat has expired. Start a new one.");
  if (result.storedResponse) return { ...result.storedResponse, duplicate: true };
  return await takeTurn(ctx, result);
}

export type WaitingQuestion = { key: string; text: string; source: "reviewer" | "model" | "rules"; askedAt: number | null };

/**
 * What the bank is still waiting to hear from the customer on a case, in the order a call or chat
 * asks it: reviewers' questions, then the reasoning model's current question, or the rules'
 * questions when the model has none.
 */
export const waitingQuestions = query({
  args: { caseId: v.id("cases") },
  handler: async (ctx, { caseId }): Promise<WaitingQuestion[]> => {
    const c = await ctx.db.get(caseId);
    if (!c) return [];
    const out: WaitingQuestion[] = (await openReviewerQuestions(ctx, caseId)).map((q) => ({ key: `reviewer:${q._id}`, text: q.text, source: "reviewer", askedAt: q.askedAt }));
    const mq = await modelQuestionFor(ctx, caseId);
    if (mq) out.push({ key: mq.key, text: mq.text, source: "model", askedAt: null });
    // The rules' questions are the fallback: shown only when the model has no current question.
    const rules = mq ? [] : ((c.analysis as { questions?: { key: string; text: string; audience: string }[] } | null)?.questions ?? []).filter((q) => q.audience === "customer");
    for (const q of rules) out.push({ key: q.key, text: q.text, source: "rules", askedAt: null });
    const seen = new Set<string>();
    return out.filter((q) => {
      const k = q.text.toLowerCase();
      if (seen.has(k)) return false;
      seen.add(k);
      return true;
    });
  },
});
